-- Esquema para um banco MySQL 8 vazio. IDs são gerados pela aplicação.
CREATE TABLE users (
  id CHAR(36) NOT NULL PRIMARY KEY,
  email VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  name VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'recepcao',
  avatar TEXT,
  professional_id CHAR(36),
  created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE patients (
  id CHAR(36) NOT NULL PRIMARY KEY,
  code VARCHAR(50) UNIQUE,
  name VARCHAR(255) NOT NULL,
  cpf VARCHAR(14) NOT NULL UNIQUE,
  birth DATE,
  sex CHAR(1),
  phone VARCHAR(20),
  whatsapp VARCHAR(20),
  email VARCHAR(255),
  address TEXT,
  emergency_contact VARCHAR(255),
  insurance VARCHAR(255),
  insurance_card VARCHAR(255),
  allergies JSON DEFAULT (JSON_ARRAY()),
  medications JSON DEFAULT (JSON_ARRAY()),
  notes TEXT,
  created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  INDEX idx_patients_email (email)
) ENGINE=InnoDB;

CREATE TABLE appointments (
  id CHAR(36) NOT NULL PRIMARY KEY,
  patient_id CHAR(36) NOT NULL,
  professional_id CHAR(36) NOT NULL,
  unit_id VARCHAR(50),
  date DATE NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  type VARCHAR(50) NOT NULL DEFAULT 'consulta',
  specialty VARCHAR(100),
  `procedure` VARCHAR(255),
  insurance VARCHAR(255),
  value DECIMAL(10, 2),
  payment_method VARCHAR(50),
  status VARCHAR(50) NOT NULL DEFAULT 'agendado',
  notes TEXT,
  telehealth_url TEXT,
  created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  FOREIGN KEY (professional_id) REFERENCES users(id),
  INDEX idx_appointments_date (date),
  INDEX idx_appointments_professional_date (professional_id, date)
) ENGINE=InnoDB;

CREATE TABLE soap_notes (
  id CHAR(36) NOT NULL PRIMARY KEY,
  patient_id CHAR(36) NOT NULL,
  professional_id CHAR(36) NOT NULL,
  appointment_id CHAR(36),
  queixa TEXT NOT NULL,
  hda TEXT,
  antecedentes TEXT,
  medicamentos TEXT,
  alergias TEXT,
  habitos TEXT,
  pa VARCHAR(20),
  fc VARCHAR(20),
  fr VARCHAR(20),
  temp VARCHAR(20),
  spo2 VARCHAR(20),
  peso VARCHAR(20),
  altura VARCHAR(20),
  subjetivo TEXT NOT NULL,
  objetivo TEXT NOT NULL,
  avaliacao TEXT NOT NULL,
  plano TEXT NOT NULL,
  hipotese TEXT,
  diagnostico VARCHAR(50),
  conduta TEXT,
  retorno VARCHAR(100),
  anexos JSON DEFAULT (JSON_ARRAY()),
  adendos JSON DEFAULT (JSON_ARRAY()),
  signed BOOLEAN DEFAULT FALSE,
  signed_at DATETIME(6),
  version BIGINT NOT NULL DEFAULT 1,
  created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  FOREIGN KEY (professional_id) REFERENCES users(id),
  INDEX idx_soap_notes_appointment_id (appointment_id)
) ENGINE=InnoDB;

CREATE TABLE prescriptions (
  id CHAR(36) NOT NULL PRIMARY KEY,
  patient_id CHAR(36) NOT NULL,
  professional_id CHAR(36) NOT NULL,
  soap_note_id CHAR(36),
  date DATE NOT NULL,
  items JSON NOT NULL DEFAULT (JSON_ARRAY()),
  observations TEXT,
  type VARCHAR(50) NOT NULL DEFAULT 'simples',
  valid_from DATE NOT NULL,
  valid_until DATE,
  status VARCHAR(50) NOT NULL DEFAULT 'ativa',
  created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  FOREIGN KEY (professional_id) REFERENCES users(id),
  FOREIGN KEY (soap_note_id) REFERENCES soap_notes(id),
  INDEX idx_prescriptions_status (status)
) ENGINE=InnoDB;

CREATE TABLE exam_orders (
  id CHAR(36) NOT NULL PRIMARY KEY,
  patient_id CHAR(36) NOT NULL,
  professional_id CHAR(36) NOT NULL,
  soap_note_id CHAR(36),
  date DATE NOT NULL,
  exams JSON NOT NULL DEFAULT (JSON_ARRAY()),
  status VARCHAR(50) NOT NULL DEFAULT 'solicitado',
  observations TEXT,
  lab_name VARCHAR(255),
  lab_phone VARCHAR(20),
  priority VARCHAR(50) DEFAULT 'normal',
  unit_id VARCHAR(50),
  result_data JSON,
  created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  FOREIGN KEY (professional_id) REFERENCES users(id),
  FOREIGN KEY (soap_note_id) REFERENCES soap_notes(id),
  INDEX idx_exam_orders_status (status)
) ENGINE=InnoDB;

CREATE TABLE audit_logs (
  id CHAR(36) NOT NULL PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  action VARCHAR(50) NOT NULL,
  entity VARCHAR(50) NOT NULL,
  entity_id CHAR(36),
  details JSON,
  created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (user_id) REFERENCES users(id),
  INDEX idx_audit_logs_entity (entity, entity_id)
) ENGINE=InnoDB;
